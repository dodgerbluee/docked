package runner

import (
	"errors"
	"net"
	"net/http"
	"regexp"
	"strconv"
	"strings"
)

// Server-URL resolution and bash install-script generation, ported from
// Node's runnerController (getDockedUrl / detectLanIp / generateInstallScript).

// DockedURL builds the externally-reachable URL for this Docked server.
// Priority: explicit DOCKED_URL override → X-Forwarded-Proto/Host headers →
// request Host, with localhost hostnames replaced by the first LAN IP so
// remote runners (LXC, other boxes) can actually reach us.
func DockedURL(r *http.Request, override string) string {
	if override != "" {
		return strings.TrimRight(override, "/")
	}

	proto := r.Header.Get("X-Forwarded-Proto")
	if proto == "" {
		if r.TLS != nil {
			proto = "https"
		} else {
			proto = "http"
		}
	}
	host := r.Header.Get("X-Forwarded-Host")
	if host == "" {
		host = r.Host
	}

	hostname := host
	port := ""
	if i := strings.Index(host, ":"); i >= 0 {
		hostname, port = host[:i], host[i+1:]
	}
	if hostname == "localhost" || hostname == "127.0.0.1" || hostname == "::1" {
		if lanIP := detectLanIP(); lanIP != "" {
			resolved := proto + "://" + lanIP
			if port != "" {
				resolved += ":" + port
			}
			return resolved
		}
		// Node logs a warning here; runners on remote machines will not be
		// able to reach a localhost URL. Set DOCKED_URL to fix.
	}
	return proto + "://" + host
}

// detectLanIP returns the first non-internal IPv4 address, skipping Docker
// virtual interfaces (docker*, br-*, veth*) and the Docker bridge subnet
// (172.16.0.0/12). Nil-safe: returns "" when nothing suitable is found.
func detectLanIP() string {
	ifaces, err := net.Interfaces()
	if err != nil {
		return ""
	}
	for _, iface := range ifaces {
		if ifaceSkipRe.MatchString(iface.Name) {
			continue
		}
		if iface.Flags&net.FlagLoopback != 0 {
			continue
		}
		addrs, err := iface.Addrs()
		if err != nil {
			continue
		}
		for _, addr := range addrs {
			ipNet, ok := addr.(*net.IPNet)
			if !ok {
				continue
			}
			ip4 := ipNet.IP.To4()
			if ip4 == nil || ip4.IsLoopback() {
				continue
			}
			// Skip the Docker bridge subnet 172.16.0.0/12.
			if ip4[0] == 172 && ip4[1] >= 16 && ip4[1] <= 31 {
				continue
			}
			return ip4.String()
		}
	}
	return ""
}

var (
	tokenRe     = regexp.MustCompile(`^[a-f0-9]+$`)
	semverRe    = regexp.MustCompile(`^\d+\.\d+\.\d+[\w.+-]*$`)
	urlBadChars = regexp.MustCompile("[`$\\\\!#&|;()\n\r]")
	ifaceSkipRe = regexp.MustCompile(`^(docker|br-|veth)`)
)

// InstallScriptParams feeds the generated bash installer. All inputs are
// validated to prevent shell injection (same rules as Node).
type InstallScriptParams struct {
	Token           string
	DockedURL       string
	DockhandVersion string
	Port            int
}

// GenerateInstallScript renders the single-use systemd installer. Note the
// faithful quirk from Node: a non-semver version (e.g. the "latest" fallback
// when the GitHub lookup failed) is rejected — the install endpoint then
// surfaces a 500 rather than baking "latest" into the download URL.
func GenerateInstallScript(p InstallScriptParams) (string, error) {
	if !tokenRe.MatchString(strings.ToLower(p.Token)) {
		return "", errors.New("invalid enrollment token format")
	}
	if !semverRe.MatchString(p.DockhandVersion) {
		return "", errors.New("invalid dockhand version format")
	}
	if urlBadChars.MatchString(p.DockedURL) {
		return "", errors.New("invalid docked URL — contains disallowed characters")
	}
	if p.Port < 1 || p.Port > 65535 {
		return "", errors.New("invalid port number")
	}

	r := strings.NewReplacer(
		"__DOCKED_URL__", p.DockedURL,
		"__ENROLLMENT_TOKEN__", p.Token,
		"__DOCKHAND_VERSION__", p.DockhandVersion,
		"__PORT__", strconv.Itoa(p.Port),
	)
	return r.Replace(installScriptTemplate), nil
}

const installScriptTemplate = `#!/usr/bin/env bash
set -euo pipefail

# Docked Runner (dockhand) installer
# Generated by Docked — this script is single-use.

DOCKED_URL="__DOCKED_URL__"
ENROLLMENT_TOKEN="__ENROLLMENT_TOKEN__"
DOCKHAND_VERSION="__DOCKHAND_VERSION__"
PORT=__PORT__
INSTALL_DIR="/usr/local/bin"
CONFIG_DIR="/etc/dockhand"
DATA_DIR="/var/lib/dockhand"
SERVICE_USER="$(whoami)"
SERVICE_HOME="$(eval echo ~$SERVICE_USER)"

echo "==> Installing dockhand v$DOCKHAND_VERSION for user $SERVICE_USER"

# Detect architecture
ARCH="$(uname -m)"
case "$ARCH" in
  x86_64)  ARCH="amd64" ;;
  aarch64) ARCH="arm64" ;;
  armv7l)  ARCH="arm" ;;
  *)
    echo "ERROR: Unsupported architecture: $ARCH" >&2
    exit 1
    ;;
esac

echo "==> Detected architecture: $ARCH"

# Download binary
DOWNLOAD_URL="https://github.com/dockedapp/dockhand/releases/download/v$DOCKHAND_VERSION/dockhand-linux-$ARCH"
echo "==> Downloading from $DOWNLOAD_URL"
mkdir -p "$INSTALL_DIR"
curl -fsSL -o "$INSTALL_DIR/dockhand" "$DOWNLOAD_URL"
chmod +x "$INSTALL_DIR/dockhand"

echo "==> Installed binary to $INSTALL_DIR/dockhand"

# Create config directory
mkdir -p "$CONFIG_DIR"
mkdir -p "$DATA_DIR"

# Check for Docker
DOCKER_ENABLED=true
if ! command -v docker &>/dev/null; then
  DOCKER_ENABLED=false
  echo "==> Docker not found — container management will be disabled"
fi

# Write config
cat > "$CONFIG_DIR/config.yaml" <<CONF
server:
  port: $PORT

runner:
  name: "$(hostname)"
  docked_url: "$DOCKED_URL"
  enrollment_token: "$ENROLLMENT_TOKEN"

docker:
  enabled: $DOCKER_ENABLED
CONF

echo "==> Wrote config to $CONFIG_DIR/config.yaml"

# Build PATH — include common binary locations
SANE_PATH="/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"

# Create systemd unit
cat > /etc/systemd/system/dockhand.service <<UNIT
[Unit]
Description=Docked Runner Agent (dockhand)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=$SERVICE_USER
Environment=HOME=$SERVICE_HOME
Environment=PATH=$SANE_PATH
ExecStart=$INSTALL_DIR/dockhand -config $CONFIG_DIR/config.yaml
Restart=on-failure
RestartSec=5
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=multi-user.target
UNIT

# Fix ownership
chown -R "$SERVICE_USER" "$CONFIG_DIR" "$DATA_DIR"

# Enable and start
systemctl daemon-reload
systemctl enable dockhand
systemctl start dockhand

echo "==> dockhand service started"
echo "==> Waiting for registration with Docked server..."

# Wait briefly for dockhand to register
for i in $(seq 1 10); do
  if journalctl -u dockhand --no-pager -n 5 2>/dev/null | grep -q "registered"; then
    echo "==> Registration successful!"
    break
  fi
  sleep 2
done

echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "  dockhand v$DOCKHAND_VERSION installed successfully"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""
echo "  Config file:   $CONFIG_DIR/config.yaml"
echo "  Data / DB:     $DATA_DIR/"
echo "  Binary:        $INSTALL_DIR/dockhand"
echo "  Service:       dockhand (systemd)"
echo ""
echo "  Useful commands:"
echo "    systemctl status dockhand          — check service status"
echo "    journalctl -u dockhand -f          — follow live logs"
echo "    systemctl restart dockhand         — restart after config changes"
echo "    systemctl stop dockhand            — stop the service"
echo ""
echo "  Adding operations (edit the config file, then restart):"
echo "    sudo nano $CONFIG_DIR/config.yaml"
echo ""
echo "  Example operations block:"
echo "    operations:"
echo "      pull-and-restart:"
echo "        description: Pull latest images and restart compose stack"
echo "        command: docker compose -f /opt/myapp/docker-compose.yml pull && docker compose -f /opt/myapp/docker-compose.yml up -d"
echo "        working_dir: /opt/myapp"
echo "        timeout: 300"
echo ""
echo "  After editing the config, restart the service:"
echo "    sudo systemctl restart dockhand"
echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""
`
